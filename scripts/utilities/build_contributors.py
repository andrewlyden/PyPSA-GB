"""Write the docs' contributor grid from GitHub's contributor list.

Reads ``docs/source/contributors.yaml`` (repository, lead developer, the 2024 paper's co-authors, names for accounts
without a public display name, accounts to leave out) and GitHub's REST API (``/repos/{repo}/contributors``, ordered
by commits; each account's public name from ``/users/{login}``), and writes ``docs/source/_includes/contributors.html``:
one card per person (GitHub picture, name, role), lead first, then the paper's co-authors, then everyone else by
commits.

The docs build runs it (``docs/source/conf.py``); when GitHub cannot be reached the committed file stays as it is.
A ``GITHUB_TOKEN`` in the environment raises GitHub's limit of 60 unauthenticated requests an hour.

    python scripts/utilities/build_contributors.py
"""

from __future__ import annotations

import html
import json
import os
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / "docs" / "source" / "contributors.yaml"
OUT = ROOT / "docs" / "source" / "_includes" / "contributors.html"
CACHE = OUT.with_suffix(".json")   # the last list GitHub gave, so an offline build still draws the grid
ROLES = {"lead": "Lead developer", "paper": "2024 paper co-author", "code": "Code contributor"}


def _get(url: str):
    headers = {"User-Agent": "PyPSA-GB docs build", "Accept": "application/vnd.github+json"}
    if os.environ.get("GITHUB_TOKEN"):
        headers["Authorization"] = f"Bearer {os.environ['GITHUB_TOKEN']}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=20) as response:
        return json.loads(response.read().decode("utf-8"))


def contributors(config: dict) -> list[dict]:
    """One dict per person (login, name, role, url, avatar): lead, paper co-authors, then the rest by commits."""
    names = config.get("names") or {}
    exclude = set(config.get("exclude") or [])
    lead, paper = config.get("lead"), list(config.get("paper") or [])
    accounts, page = [], 1
    while True:
        batch = _get(f"https://api.github.com/repos/{config['repository']}/contributors?per_page=100&page={page}")
        if not batch:
            break
        accounts += [a for a in batch if a.get("login") and a["login"] not in exclude and a.get("type") != "Bot"]
        if len(batch) < 100:
            break
        page += 1
    people = []
    for account in accounts:
        login = account["login"]
        name = names.get(login) or (_get(f"https://api.github.com/users/{login}").get("name") or "").strip() or login
        role = "lead" if login == lead else "paper" if login in paper else "code"
        people.append({"login": login, "name": name, "role": role,
                       "url": account.get("html_url") or f"https://github.com/{login}"})
    order = {"lead": 0, "paper": 1, "code": 2}
    people.sort(key=lambda p: (order[p["role"]], paper.index(p["login"]) if p["role"] == "paper" else 0))
    return people


def render(people: list[dict]) -> str:
    cards = "\n".join(
        f'     <a class="pgb-person" href="{html.escape(p["url"])}">'
        f'<img src="https://github.com/{html.escape(p["login"])}.png?size=120" alt="" loading="lazy">'
        f'<span class="pgb-person-name">{html.escape(p["name"])}</span>'
        f'<span class="pgb-person-role">{ROLES[p["role"]]}</span></a>'
        for p in people)
    return ("<!-- Generated by scripts/utilities/build_contributors.py from GitHub's contributor list; do not edit. -->\n"
            "<div class=\"pgb-people\">\n" + cards + "\n</div>\n")


def main() -> None:
    config = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))
    try:
        people = contributors(config)
        CACHE.write_text(json.dumps(people, indent=1), encoding="utf-8")
    except Exception as error:   # offline or rate-limited: draw the grid from the last list
        if not CACHE.exists():
            raise
        print(f"GitHub not reached ({error}); using {CACHE.name}")
        people = json.loads(CACHE.read_text(encoding="utf-8"))
    text = render(people)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        OUT.write_text(text, encoding="utf-8")
    print(f"{OUT}: written")


if __name__ == "__main__":
    main()
